def _read(path):
    """imdecode also supports non-ASCII Windows checkout paths."""
    return cv2.imdecode(np.fromfile(str(path), dtype=np.uint8), cv2.IMREAD_COLOR)


def face_region(crop):
    """Remove gold bases/selection caps using the longest cream row interval."""
    if crop is None or crop.size == 0:
        raise ValueError('empty tile crop')
    h, w = crop.shape[:2]
    hsv = cv2.cvtColor(crop, cv2.COLOR_BGR2HSV)
    cream = (hsv[:, :, 1] < 90) & (hsv[:, :, 2] > 65)
    # Broad �?bird glyphs can touch either side; use low cream coverage and
    # bridge only short glyph interruptions, never the tall gold selection cap.
    a,b=max(1,int(w*.05)),min(w-1,int(w*.95))
    rows = (np.mean(cream[:,a:b],axis=1) > .23).astype(np.uint8)
    rows = cv2.morphologyEx(rows[:,None],cv2.MORPH_CLOSE,np.ones((7,1),np.uint8))[:,0]>0
    intervals, start = [], None
    for i, on in enumerate(np.r_[rows, False]):
        if on and start is None:
            start = i
        if not on and start is not None:
            intervals.append((start, i)); start = None
    if not intervals:
        return crop
    y0, y1 = max(intervals, key=lambda p: p[1]-p[0])
    if y1-y0 < h*.35:
        return crop
    return crop[y0:y1, :]


def tile_signature(crop):
    """Fit real glyph pixels to a fixed canvas; discard skin brightness changes.

    Red, green and dark ink are separate channels. White faces alone therefore
    cannot produce a high match, unlike whole-tile grayscale correlation.
    """
    face = face_region(crop)
    h, w = face.shape[:2]
    dy, dx = max(2, int(h*.05)), max(2, int(w*.07))
    inner = face[dy:h-dy, dx:w-dx]
    if inner.size == 0:
        return None
    hsv = cv2.cvtColor(inner, cv2.COLOR_BGR2HSV)
    gray = cv2.cvtColor(inner, cv2.COLOR_BGR2GRAY)
    hue, sat, val = (hsv[:, :, i] for i in range(3))
    background = float(np.percentile(gray, 75))
    red = ((hue < 19) | (hue > 165)) & (sat > 100) & (val > 35)
    green = (hue >= 32) & (hue <= 95) & (sat > 90) & (val > 35)
    # Navy numerals are highly saturated too; exclude red/green by hue instead
    # of excluding all saturated dark ink (which loses the numeral above �?.
    dark = (gray < max(35., background*.62)) & ~red & ~green
    # The actual target recordings overlay a yellow �?word on a red corner
    # triangle. Detect both colours together; an ordinary red tile stroke or
    # a gold bevel alone must not trigger this mask. Only the observed corner
    # is ignored, preserving the real glyph pixels underneath/elsewhere.
    cy,cx=max(1,round(inner.shape[0]*.40)),max(1,round(inner.shape[1]*.42))
    badge_red=(hue[:cy,:cx]<8)&(sat[:cy,:cx]>130)&(val[:cy,:cx]>90)
    badge_yellow=(hue[:cy,:cx]>=18)&(hue[:cy,:cx]<=40)&(sat[:cy,:cx]>110)&(val[:cy,:cx]>150)
    if np.count_nonzero(badge_red)>cy*cx*.10 and np.count_nonzero(badge_yellow)>cy*cx*.05:
        search_h,search_w=round(inner.shape[0]*.65),round(inner.shape[1]*.72)
        fill=(hue[:search_h,:search_w]<8)&(sat[:search_h,:search_w]>130)&(val[:search_h,:search_w]>90)
        fy,fx=np.where(fill)
        if len(fx):
            bw,bh=float(np.percentile(fx,99)+3),float(np.percentile(fy,99)+3)
            yy,xx=np.indices(inner.shape[:2])
            triangle=xx/max(1,bw)+yy/max(1,bh)<=1.10
            red[triangle]=False;green[triangle]=False;dark[triangle]=False
    ink = (dark | red | green).astype(np.uint8)
    num, labels, stats, _ = cv2.connectedComponentsWithStats(ink, 8)
    clean = np.zeros_like(ink)
    for i in range(1, num):
        sx,sy,sw,sh,area=stats[i]
        # Small black/gold direction markers sit on the top border. Keep broad
        # or tall tile strokes; remove only a separate short border component.
        if sy<=1 and sh<inner.shape[0]*.17 and sw<inner.shape[1]*.55:
            continue
        if stats[i, cv2.CC_STAT_AREA] >= max(4, inner.shape[0]*inner.shape[1]*.001):
            clean[labels == i] = 1
    ys, xs = np.where(clean > 0)
    if len(xs) < 16:
        return None
    x0, x1, y0, y1 = xs.min(), xs.max()+1, ys.min(), ys.max()+1
    glyph = np.stack((dark, red, green), axis=2).astype(np.float32)
    glyph *= clean[:, :, None]
    glyph = glyph[y0:y1, x0:x1]
    gh, gw = glyph.shape[:2]
    scale = min(56/gw, 80/gh)
    nw, nh = max(1, round(gw*scale)), max(1, round(gh*scale))
    glyph = cv2.resize(glyph, (nw, nh), interpolation=cv2.INTER_AREA)
    canvas = np.zeros((88, 64, 3), np.float32)
    cy, cx = (88-nh)//2, (64-nw)//2
    canvas[cy:cy+nh, cx:cx+nw] = glyph
    # Light blur tolerates anti-aliasing/one-pixel edges without losing strokes.
    canvas = cv2.GaussianBlur(canvas, (3, 3), .6)
    norm = float(np.linalg.norm(canvas))
    return canvas / norm if norm > .001 else None


# --- 财神高亮 / 整手压暗的亮度补偿 -------------------------------------------
# 实测（1600x900 实战帧，3684 个手牌框）：普通牌面底色 p70(V)=238-245；被游戏
# "财"高亮框住的财神牌、以及"请出牌"整手压暗时，同一张牌只剩 100-115。模板签名
# 是用亮底建的，暗底把笔画/底色对比压掉三分之二，分数直接掉到 0.27-0.40，整帧
# 因此被判"识牌不完整"。这里只做一次线性增益把底色调回模板的亮度基准；已经够亮
# 的牌原样返回，所以既有帧的输入和结论逐字节不变。
_FACE_BG_BELOW = 200.0
_FACE_BG_REFERENCE = 238.0

# 实测（同 3684 个牌框）：红"财"角标占左上角标窗口 46.3%-48.8%，内部必有金色
# "财"笔画 9.4%-12.3%；其余牌框最高只有 13.7% 红 / 14.1% 金。两个条件同时成立
# 时 3684 个牌框零误报，所以角标可以作为"这张就是本局财神牌"的确定性证据。
_BADGE_RED_FRACTION = 0.30
_BADGE_GOLD_FRACTION = 0.04

# --- 整张纯金"财神牌"的手牌框（count_tiles 金色通道） -------------------------
# 实测（2026-10-25 23:31 房间 915995 实机帧 emulator-5556
# / 20261025_233119_686643_before_684d78.png，1600x900）：本局两张财神牌被渲成
# 整块金黄、牌面完全空白——没有奶油底色、也没有任何牌面墨迹。既有"奶油低饱和
# 连通列"通道对它们一个像素都不命中，暗手只数到 12 框（实际 14），tea_bot 因此
# 抛"暗手应为13或14张"整帧弃权。取样（同一帧）：
#   两张金内区 85x116：H=18-21、S p1=223 / mean=230、V p1=157、灰度 mean=162 std=26；
#   普通牌面 八萬/三萬/六条/北：灰度 mean=178-183 std=63-75，S mean=22-104，
#   H 跨度 0-111，整块金色占比最高只有 0.172。
# 所以"窄色相 + 高饱和 + 低灰度方差"能整块圈住金色牌，又碰不到普通牌面：
# 3 张六条明牌组、三萬、八萬等普通牌的金色占比与灰度方差都远在阈值之外。
_GOLD_HUE = (14, 32)          # 金内区实测 H=18-21，两侧各留余量
_GOLD_MIN_SAT = 150           # 金内区实测 S>=223；普通牌面 S mean<=104
_GOLD_MIN_VAL = 110           # 金内区实测 V p1=157；避开压暗牌的深色边线与阴影
_GOLD_MIN_FRACTION = .75      # 整块金色占比：金内区实测 0.992，普通牌最高 0.172
_GOLD_MAX_INK_STD = 40.0      # 牌面无墨迹的证据：金内区 std=26，普通牌最低 63


def face_background(crop):
    """Return p70(V) of the tile face: the brightness level templates encode."""
    face = face_region(crop)
    hsv = cv2.cvtColor(face, cv2.COLOR_BGR2HSV)
    return float(np.percentile(hsv[:, :, 2], 70))


def normalise_face_brightness(crop, reference=_FACE_BG_REFERENCE,
                              below=_FACE_BG_BELOW):
    """Gain a greyed/dimmed tile face back to ordinary hand-tile brightness.

    The game renders the 财-marked caishen tile, and the whole hand during the
    "discard now" pause, at roughly half brightness. A plain linear gain feeds
    the existing templates the same contrast they were measured on, so the real
    glyph decides the label instead of the highlight being guessed around.
    """
    if crop is None or crop.size == 0:
        return crop
    background = face_background(crop)
    if background <= 1.0 or background >= below:
        return crop
    return np.clip(crop.astype(np.float32)*(reference/background),
                   0, 255).astype(np.uint8)


def caishen_badge(crop):
    """Return True when the tile carries the game's red 财 corner banner."""
    if crop is None or crop.size == 0:
        return False
    height, width = crop.shape[:2]
    window = crop[:max(10, round(height*.32)),
                  :max(12, round(width*.36))].astype(np.int16)
    blue, green, red = window[:, :, 0], window[:, :, 1], window[:, :, 2]
    # Ratios rather than absolute levels: the same banner is drawn on a bright
    # tile and on a greyed one, so only the colour relationship survives.
    red_mask = (red-green > 50) & (red-blue > 50) & (red > 70)
    gold_mask = ((red > 70) & (green*100 > red*45) & (green*100 < red*82)
                 & (blue*100 < red*58) & (green-blue > 18))
    area = float(window.shape[0]*window.shape[1])
    return (float(np.count_nonzero(red_mask))/area >= _BADGE_RED_FRACTION
            and float(np.count_nonzero(gold_mask))/area >= _BADGE_GOLD_FRACTION)


def gold_face_mask(crop):
    """Boolean mask of the near-solid gold used by a whole-gold caishen tile."""
    hsv = cv2.cvtColor(crop, cv2.COLOR_BGR2HSV)
    return ((hsv[:, :, 0] >= _GOLD_HUE[0]) & (hsv[:, :, 0] <= _GOLD_HUE[1])
            & (hsv[:, :, 1] >= _GOLD_MIN_SAT) & (hsv[:, :, 2] >= _GOLD_MIN_VAL))


def gold_tile_evidence(crop):
    """Return ``(gold_fraction, ink_std)`` for one candidate tile crop.

    A whole-gold caishen tile is uniformly gold with no glyph ink at all, so its
    gold fraction is ~1 and its grayscale spread is tiny. An ordinary face has
    cream base plus dark/red/green strokes: gold fraction stays under 0.20 and
    the grayscale standard deviation is 63 or more (measured, see constants).
    """
    if crop is None or crop.size == 0:
        return 0.0, float('inf')
    fraction = float(np.count_nonzero(gold_face_mask(crop)))/float(crop.shape[0]*crop.shape[1])
    return fraction, float(cv2.cvtColor(crop, cv2.COLOR_BGR2GRAY).std())


def is_gold_tile(crop):
    """True only for an unprinted, fully gold tile (the extreme caishen marking)."""
    fraction, ink_std = gold_tile_evidence(crop)
    return fraction >= _GOLD_MIN_FRACTION and ink_std <= _GOLD_MAX_INK_STD


# --- 吃碰杠"来源箭头"（claim marker）去遮挡 -------------------------------------
# 实测（2026-10-23/24 实战帧，wrong_count 弃权的根因）：副露组里被吃/碰的那张牌
# 顶边正中会叠一个半透明黑圆 + 实心黄色三角箭头。黑圆把牌面上沿压暗到约 0.53 倍，
# 被签名当作墨迹并入字形外框，三万/二万/四万/二筒等牌分数从 ≥0.94 掉到 0.51-0.78，
# 整组副露"识牌不完整"，整帧弃权。这里在分类前把黑圆按实测透明度除回去、把黄三角
# 涂成牌面底色；没有箭头的牌原样返回（同一对象），既有帧的输入与结论逐字节不变。
_MARKER_BAND = .16          # 箭头只出现在牌面最上沿这一条带内
_MARKER_MIN_PIXELS = 12     # 黄色三角最少像素（实测 1600x900 下约 110-120）


def strip_claim_marker(crop):
    """Undo the translucent claim-marker disc drawn over a tile's top edge.

    Returns ``(crop, found)``. ``crop`` is the untouched input object when no
    marker is present, so callers without a marker see identical pixels.
    Only observed yellow pixels are opaque-triangle evidence. Dilating this
    paint mask can erase adjacent visible information and change a readable
    glyph; leave that unproven halo untouched in both marker layouts.
    """
    if crop is None or crop.size == 0 or crop.ndim != 3:
        return crop, False
    h, w = crop.shape[:2]
    band_h = max(6, int(round(h*_MARKER_BAND)))
    if band_h >= h - 4:
        return crop, False
    hsv = cv2.cvtColor(crop, cv2.COLOR_BGR2HSV)
    hue, sat, val = hsv[:band_h, :, 0], hsv[:band_h, :, 1], hsv[:band_h, :, 2]
    yellow = (hue >= 15) & (hue <= 40) & (sat > 110) & (val > 150)
    ys, xs = np.nonzero(yellow)
    if len(xs) < max(_MARKER_MIN_PIXELS, int(w*h*.0012)):
        return crop, False
    centre = float(xs.mean())
    # Centred and narrow: rules out the top-left 财 banner and full-width rims.
    if not (.3*w <= centre <= .7*w) or xs.max() - xs.min() > .3*w:
        return crop, False
    background = float(np.percentile(hsv[band_h:, :, 2], 70))
    if background < 150:
        return crop, False
    shade = (val >= background*.40) & (val <= background*.66) & (sat < 70)
    seed = cv2.dilate(yellow.astype(np.uint8), np.ones((5, 5), np.uint8)) > 0
    _, labels = cv2.connectedComponents((shade | yellow).astype(np.uint8), connectivity=8)
    keep = set(np.unique(labels[seed]).tolist()) - {0}
    if not keep:
        return crop, False
    disc = np.isin(labels, list(keep))
    if np.count_nonzero(disc & shade) < 20:
        # A newly claimed meld can sit flush with the bottom edge.  In that
        # layout the black source disc is above the detected tile box and only
        # the centred yellow triangle is clipped into the crop.  Requiring the
        # disc here leaves the triangle inside the glyph signature (the real
        # 2026-10-27 4-5-6 chi then read its leading 4万 as a weak 9万).
        #
        # Recover only this clipped form: the compact triangle must enter from
        # the crop's top edge and extend through almost the whole marker band.
        # The earlier centre/span checks still exclude the top-left 财神 badge
        # and the full-width gold selection cap.  We remove only the opaque
        # triangle; no hidden glyph pixels or tile label are invented.
        clipped_triangle = (
            int(ys.min()) == 0
            and int(ys.max()) >= band_h - 3
            and int(np.count_nonzero(yellow[0])) >= max(6, int(round(w*.07)))
        )
        if not clipped_triangle:
            return crop, False
        out = crop.copy()
        tri = np.zeros((h, w), bool)
        tri[:band_h] = yellow
        lower = crop[band_h:]
        face_pixels = lower[hsv[band_h:, :, 2] >= background*.95]
        if not len(face_pixels):
            return crop, False
        out[tri] = np.median(face_pixels, axis=0).astype(np.uint8)
        return out, True
    dys, dxs = np.nonzero(disc)
    (cx, cy), radius = cv2.minEnclosingCircle(
        np.stack([dxs, dys], 1).astype(np.float32))
    if radius > .32*w:
        return crop, False
    factor = float(np.median(val[disc & shade]))/background
    if not (.35 <= factor <= .75):
        return crop, False
    out = crop.copy()
    yy, xx = np.indices((h, w))
    inside = (xx-cx)**2 + (yy-cy)**2 <= (radius+1.5)**2
    out[inside] = np.clip(out[inside].astype(np.float32)/factor, 0, 255).astype(np.uint8)
    # The opaque triangle hides whatever is below it: paint plain face colour.
    tri = np.zeros((h, w), bool)
    tri[:band_h] = yellow
    lower = crop[band_h:]
    face_pixels = lower[hsv[band_h:, :, 2] >= background*.95]
    if len(face_pixels):
        out[tri] = np.median(face_pixels, axis=0).astype(np.uint8)
    return out, True


# Static template signatures are shared; observations and round state never are.
# A new vision instance revalidates all referenced files before reusing a bank.
# Keep only the latest bank per directory and bound the number of directories.
_TEMPLATE_BANK_LIMIT = 4
_TEMPLATE_BANKS = OrderedDict()
_TEMPLATE_BANK_LOCK = RLock()


@dataclass(frozen=True)
class _TemplateBank:
    fingerprint: tuple
    paths: tuple
    templates: tuple
    matrix: np.ndarray


def _template_file_stamp(path):
    stat = path.stat()
    return (stat.st_mtime_ns, stat.st_ctime_ns, stat.st_size,
            stat.st_dev, stat.st_ino)


def _immutable_array(array):
    # bytes-backed arrays cannot be made writable by another vision instance.
    return np.frombuffer(array.tobytes(), dtype=array.dtype).reshape(array.shape)


def _load_template_bank(template_dir):
    directory = Path(template_dir).resolve()
    manifest = directory / 'manifest.json'
    cache_key = os.path.normcase(str(directory))
    with _TEMPLATE_BANK_LOCK:
        try:
            try:
                manifest_stamp = _template_file_stamp(manifest)
            except FileNotFoundError as exc:
                raise NoTemplatesError(
                    f'verified template manifest missing: {manifest}') from exc
            cached = _TEMPLATE_BANKS.get(cache_key)
            if cached is not None:
                current = (manifest_stamp, tuple(
                    _template_file_stamp(path) for path in cached.paths))
                if current == cached.fingerprint:
                    _TEMPLATE_BANKS.move_to_end(cache_key)
                    return cached
                _TEMPLATE_BANKS.pop(cache_key, None)

            records = json.loads(
                manifest.read_text(encoding='utf-8'))['templates']
            paths = tuple(directory / rec['file'] for rec in records)
            fingerprint = (manifest_stamp, tuple(
                _template_file_stamp(path) for path in paths))
            templates = []
            for rec, path in zip(records, paths):
                crop = _read(path)
                sig = tile_signature(crop)
                if sig is None:
                    raise NoTemplatesError(
                        f'template has no usable glyph: {rec["file"]}')
                templates.append((rec['label'], TILE_IDS[rec['label']],
                                  _immutable_array(sig)))
            if not templates:
                raise NoTemplatesError('no verified tile templates')
            matrix = _immutable_array(
                np.stack([item[2].ravel() for item in templates]))
            current = (_template_file_stamp(manifest), tuple(
                _template_file_stamp(path) for path in paths))
            if current != fingerprint:
                raise NoTemplatesError('template files changed while loading')

            bank = _TemplateBank(fingerprint, paths, tuple(templates), matrix)
            _TEMPLATE_BANKS[cache_key] = bank
            _TEMPLATE_BANKS.move_to_end(cache_key)
            while len(_TEMPLATE_BANKS) > _TEMPLATE_BANK_LIMIT:
                _TEMPLATE_BANKS.popitem(last=False)
            return bank
        except Exception:
            # Missing/corrupt/changing assets must never fall back to an old bank.
            _TEMPLATE_BANKS.pop(cache_key, None)
            raise


class TileVision:
    def __init__(self, template_dir=None, min_score=.82, min_margin=.055,
                 caishen_label=None, *, allow_claim_marker=True):
        self.template_dir = Path(template_dir or BASE_DIR/'templates_hongzhong_v2')
        self.min_score = min_score
        self.min_margin = min_margin
        # 本局财神 label（vision 词汇，如 's4'）。None=未知，此时角标不填牌。
        self.caishen_label = caishen_label
        # Meld source arrows may require de-occlusion; river discard pointers
        # are a different overlay and must keep their original glyph pixels.
        self.allow_claim_marker = bool(allow_claim_marker)
        self.diagnostics = []
        self.detection_diagnostics = {}
        self.last_meld_boxes = []
        self.last_gold_boxes = []
        # 实验开关：整手压暗时是否也做亮度补偿（默认关闭，见 _classify_detected_box）。
        # 置环境变量 WZMJ_DIM_GAIN=1 才打开；默认路径与既有弃权契约完全一致。
        self.dim_gain_all = os.environ.get('WZMJ_DIM_GAIN', '') not in ('', '0')
        self.last_melds = []
        self.meld_diagnostics = []
        self.last_complete = False
        self.templates = []
        self._matrix = None
        self._loaded = False

    def load_templates(self):
        if self._loaded:
            return
        bank = _load_template_bank(self.template_dir)
        # The list remains instance-local for compatibility; all shared arrays
        # are immutable.  No diagnostics, caishen or meld state enters the bank.
        self.templates = list(bank.templates)
        self._matrix = bank.matrix
        self._loaded = True

    def count_tiles(self, img, roi=None):
        """Return concealed xyxy boxes; expose separate left meld-box geometry.

        Any visibly smaller, raised left group separated from the hand is
        labelled exposed. Geometry does not infer peng/gang type or who fed it.
        """
        self.last_meld_boxes=[]
        self.last_gold_boxes=[]
        h, w = img.shape[:2]
        if roi is None:
            roi = (0, round(h*.8), w, h)
        x0, y0, x1, y1 = map(int, roi)
        x0, y0, x1, y1 = max(0,x0), max(0,y0), min(w,x1), min(h,y1)
        if x1 <= x0 or y1 <= y0:
            self.detection_diagnostics={'reason':'empty_roi','unresolved_regions':[]}
            return 0, []
        band = img[y0:y1, x0:x1]
        hsv = cv2.cvtColor(band, cv2.COLOR_BGR2HSV)
        mask = cv2.inRange(hsv, np.array([0, 0, 70]), np.array([179, 85, 255]))
        scale = w/1600
        # Find actual dark vertical borders. The 90th percentile suppresses
        # glyph ink (each glyph column still has cream rows), while a border is
        # darker throughout the face. This works with both the 90px sample skin
        # and 83/113px archived target layouts; screen width is not tile pitch.
        gray=cv2.cvtColor(band,cv2.COLOR_BGR2GRAY)
        # Upper table discards/selection markers may overhang one hand tile.
        # Estimate skin from the lower two thirds, where the hand faces lie.
        skin_rows=gray[gray.shape[0]//3:]
        column_skin=np.percentile(skin_rows,90,axis=0).astype(np.float32)
        edge_window=max(5,round(17*scale))|1
        local_skin=cv2.dilate(column_skin[None,:],np.ones((1,edge_window),np.uint8))[0]
        low_skin=column_skin < local_skin*.82
        # A raised card / bright indicator above one tile can alter a broad
        # part of the percentile profile. Real face borders are narrow; do not
        # erase wide patches and thereby silently lose a selected tile.
        visible_border=np.zeros_like(low_skin)
        ld=np.diff(np.r_[False,low_skin,False].astype(np.int8))
        for a,b in zip(np.flatnonzero(ld==1),np.flatnonzero(ld==-1)):
            if b-a<=max(5,round(11*scale)):
                visible_border[a:b]=True
        # A �?corner overlay plus a long �?stroke can cover most of a column;
        # a few real cream rows are sufficient once vertical borders are known.
        on = (np.count_nonzero(mask, axis=0) >= max(12*scale, band.shape[0]*.07))
        on &= ~visible_border
        runs = self._merged_column_runs(on, scale)
        boxes, unresolved = self._band_boxes(band, mask, runs, scale, (x0, y0))
        # 整张纯金的财神牌没有任何奶油底色，上面的通道整块漏检（实测 20261025
        # 233119 帧暗手少 2 框 = "暗手应为13或14张"弃权的根因）。金色牌因此走一条
        # 独立的列通道，但几何约束、run 起点/终点与合并算法与普通牌完全一致。
        gold_mask = gold_face_mask(band)
        gold_on = (np.count_nonzero(gold_mask, axis=0)
                   >= max(12*scale, band.shape[0]*.07))
        gold_runs = self._merged_column_runs(gold_on, scale)
        gold_boxes, _ = self._band_boxes(band, gold_mask, gold_runs, scale, (x0, y0),
                                         collect_unresolved=False)
        # 双重保险：既要整块金色、牌面无墨迹，也不许与已认出的普通牌框重叠。
        # 手牌底沿/顶沿的贴金装饰条是宽而薄的 run，会被高度/宽高比筛掉。
        gold_boxes = [box for box in gold_boxes
                      if not any(box[0] < eb[2] and eb[0] < box[2] for eb in boxes)
                      and is_gold_tile(img[box[1]:box[3], box[0]:box[2]])]
        boxes.sort(key=lambda b: b[0])
        visible_count = len(boxes) + len(gold_boxes)
        meld_groups=[]
        if len(boxes)>=6:
            melds, boxes, meld_groups = self._split_exposed_prefix(boxes, scale)
            self.last_meld_boxes = melds
        # 金色牌在露牌组切分之后才并入暗手：实测这两张金的左边缘与明牌组右边缘
        # 只差 2-15px，先并入会把 _split_exposed_prefix 的"组-手必须留真间隔"判据
        # 压到阈值以下而拒绝切分，把三张六条明牌整组吞回暗手。它们本来就落在手牌
        # 基线上、并已按同一几何约束单独成框，只是不参与明牌组的平台判定。
        self.last_gold_boxes = list(gold_boxes)
        boxes = sorted(list(boxes) + list(gold_boxes), key=lambda b: b[0])
        self.detection_diagnostics={'reason':'visible_borders','unresolved_regions':unresolved,
                                    'roi':[x0,y0,x1,y1], 'visible_count':visible_count,
                                    'concealed_count':len(boxes),'meld_boxes':[list(b) for b in self.last_meld_boxes],
                                    'meld_groups':meld_groups,
                                    'gold_boxes':[list(b) for b in self.last_gold_boxes]}
        return len(boxes), boxes

    @staticmethod
    def _merged_column_runs(column_on, scale):
        """Turn an "on" column profile into tile-width runs, merging split faces.

        A glyph column can split one face into two runs; both are then dropped
        by the width filter in `_band_boxes` (20261024_015126: the 7 of 5-6-7
        dots was lost this way, turning a legal chi into an illegal 2-tile
        group). Merge only when BOTH sides are narrower than a single tile, the
        gap is far below any real group gap, and the result still fits one tile.
        """
        changes = np.diff(np.r_[False, column_on, False].astype(np.int8))
        runs = zip(np.flatnonzero(changes==1), np.flatnonzero(changes==-1))
        merged_runs = []
        for a, b in runs:
            if merged_runs:
                pa, pb = merged_runs[-1]
                if (pb - pa) < 48*scale and (b - a) < 48*scale \
                        and (a - pb) < 6*scale and (b - pa) <= 125*scale:
                    merged_runs[-1] = (pa, b)
                    continue
            merged_runs.append((a, b))
        return merged_runs

    @staticmethod
    def _band_boxes(band, mask, runs, scale, origin, *, collect_unresolved=True):
        """Share one geometry contract between the cream and gold column runs."""
        x0, y0 = origin
        boxes,unresolved = [],[]
        for a,b in runs:
            if b-a < 48*scale:
                continue
            bx,ex=int(a),int(b);bw=ex-bx
            rows=np.flatnonzero(np.count_nonzero(mask[:,bx:ex],axis=1) >= bw*.4)
            if not len(rows):continue
            by,ey=int(rows[0]),int(rows[-1])+1;bh=ey-by
            candidate=band[by:ey,bx:ex]
            face=face_region(candidate)
            offset=(face.ctypes.data-candidate.ctypes.data)//candidate.strides[0]
            by+=int(offset);ey=by+face.shape[0];bh=ey-by
            if bw>125*scale:
                if collect_unresolved:
                    unresolved.append([x0+bx,y0+by,x0+ex,y0+ey])
                continue # Do not invent a grid when real separators are hidden.
            if not (48*scale<=bw<=125*scale and 80*scale<=bh<=180*scale):continue
            if not (.42<=bw/bh<=1.05):continue
            boxes.append((x0+bx,y0+by,x0+ex,y0+ey))
        return boxes, unresolved

    @staticmethod
    def _same_suit_run(ids):
        """True when exactly three tile ids form one consecutive same-suit run."""
        if len(set(ids)) != 3:
            return False
        return any(all(lo <= t <= hi for t in ids) and max(ids) - min(ids) == 2
                   for lo, hi in ((1, 9), (21, 29), (41, 49)))

    @classmethod
    def _meld_face_group_ok(cls, faces):
        """Return whether one fully-read geometric group can be a real meld."""
        if len(faces) not in (3, 4) or not all(d.get('accepted') for d in faces):
            return False
        ids = [d.get('tile_id') for d in faces]
        if any(tile_id is None for tile_id in ids):
            return False
        if len(set(ids)) == 1:
            return True
        return len(ids) == 3 and cls._same_suit_run(ids)

    def _classify_detected_box(self, img, box, caishen_label, *,
                               typical_width, next_left=None,
                               allow_dim_right_edge_retry=False):
        """Classify one detected box, repairing only a clipped blank tile.

        白板中间几乎没有墨迹，竖边检测偶尔会在右侧过早结束。只有原裁框明显
        偏窄、top-1 已是白板、并且右侧确有足够空位时，才把同一物理框扩到本帧
        中位牌宽重拍一次；其他牌、其他失败原因一律保持原判。
        """
        x0, y0, x1, y1 = box
        result = self.classify_crop(img[y0:y1, x0:x1],
                                    caishen_label=caishen_label)
        width = x1 - x0
        # 只给多亮压暗补读器一个受限的几何复核：实机连续 23 帧里同一张
        # 九条的右边界少 1px，原分 0.819996 仅因四舍五入前低于 0.82 被拒；
        # 补 1px 后同一 top-1 升到 0.881145。阈值与模板都不改，只在原判
        # low_score、分数紧邻门槛、右侧确有 1px 空位且重拍被正常阈值接受时
        # 采用。普通识牌和副露识牌完全不走这条分支。
        retry_limit = img.shape[1] if next_left is None else int(next_left)
        if (allow_dim_right_edge_retry and self.dim_gain_all
                and not result.get('accepted')
                and result.get('reason') == 'low_score'
                and result.get('label')
                and float(result.get('score') or 0.0) >= self.min_score - .005
                and x1 + 1 <= retry_limit):
            retry = self.classify_crop(img[y0:y1, x0:x1 + 1],
                                       caishen_label=caishen_label)
            if (retry.get('accepted')
                    and retry.get('label') == result.get('label')):
                retry['reason'] = 'accepted_dim_right_edge_retry'
                retry['original_box'] = list(box)
                retry['original_score'] = result.get('score')
                return retry, (x0, y0, x1 + 1, y1)
        # 有些压暗框被右边亮牌的强边缘截窄（20:57 实机为 83px 对同手
        # 中位宽 88px，右间隔 9px）。仅当本框确实短且右侧间隔多出空间，
        # 用两种仅扩大 1/2px 的裁框重新走原分类器；两者均须以原有分数及
        # margin 门槛直接通过、且与原 top1 一致。没有邻框时无法证明空间，
        # 或任一次变牌/歧义/失败，一律沿用原弃权；不改普通识牌或副露。
        if (allow_dim_right_edge_retry and self.dim_gain_all
                and not result.get('accepted')
                and result.get('reason') == 'low_score'
                and result.get('label')
                and typical_width > 0
                and typical_width - width >= max(4, round(typical_width * .04))
                and next_left is not None
                and next_left - x1 >= max(8, round(typical_width * .09))
                and x1 + 2 < next_left):
            first = self.classify_crop(img[y0:y1, x0:x1 + 1],
                                       caishen_label=caishen_label)
            second = self.classify_crop(img[y0:y1, x0:x1 + 2],
                                        caishen_label=caishen_label)
            if all(read.get('accepted') and read.get('reason') == 'accepted'
                   and read.get('label') == result.get('label')
                   and float(read.get('score') or 0.0) >= self.min_score
                   and float(read.get('margin') or 0.0) >= self.min_margin
                   for read in (first, second)):
                second['reason'] = 'accepted_dim_geometric_edge_retry'
                second['original_box'] = list(box)
                second['original_score'] = result.get('score')
                second['retry_one_score'] = first.get('score')
                return second, (x0, y0, x1 + 2, y1)
        if (result.get('accepted') or result.get('label') != 'bai'
                or typical_width <= 0 or width >= typical_width * .80):
            return result, tuple(box)
        gap_floor = max(12, round(typical_width * .14))
        right_limit = img.shape[1] if next_left is None else next_left - gap_floor
        expanded_right = min(round(x0 + typical_width), right_limit)
        if expanded_right < x1 + max(6, round(typical_width * .08)):
            return result, tuple(box)
        retry = self.classify_crop(img[y0:y1, x0:expanded_right],
                                   caishen_label=caishen_label)
        if not (retry.get('accepted') and retry.get('label') == 'bai'):
            return result, tuple(box)
        retry['reason'] = 'accepted_narrow_bai_retry'
        retry['original_box'] = list(box)
        retry['original_score'] = result.get('score')
        return retry, (x0, y0, expanded_right, y1)

    def _realign_failed_meld_boxes(self, img, caishen_label, *,
                                   typical_width, next_left):
        """副露框重对齐的调度层：只救相关性兜底也救不回的低分框。

        顺序是刻意的：单张弱牌先由 recover_triplet 按既有契约恢复（诊断
        保留弱分与兜底 reason）；走到这里的只剩整组同灭的框——正是框切
        分带偏的签名。另外两道门：原读必须是 low_score 且分数低于阈值
        （原框已读到高分却被拒的，如人工降分/margin 不足，照旧弃权）；
        框必须属于几何组大小 3/4 的副露组。重对齐本身见 _realign_meld_box。
        """
        sizes = [int(s) for s in
                 (self.detection_diagnostics or {}).get('meld_groups') or []]
        if sum(sizes) != len(self.meld_diagnostics):
            return
        # 全帧副露框的典型中心距（原始检测口径，中位数抗坏组污染），
        # 供重对齐后的组级几何校验（见 _meld_group_geometry_ok）。
        all_boxes = [tuple(b) for b in self.last_meld_boxes]
        pitches = [
            (nxt[0] + nxt[2] - prev[0] - prev[2]) / 2.0
            for prev, nxt in zip(all_boxes, all_boxes[1:])]
        typical_pitch = float(np.median(pitches)) if pitches else 0.0
        offset = 0
        for size in sizes:
            group = list(range(offset, offset + size))
            offset += size
            if size not in (3, 4):
                continue
            saved_diags = [dict(self.meld_diagnostics[i]) for i in group]
            saved_boxes = [list(self.last_meld_boxes[i]) for i in group]
            realigned_positions = []
            for pos, i in enumerate(group):
                d = self.meld_diagnostics[i]
                if d.get('accepted'):
                    continue
                if d.get('reason') != 'low_score':
                    continue
                if float(d.get('score') or 0.0) >= self.min_score:
                    continue
                box = self.last_meld_boxes[i]
                realigned = self._realign_meld_box(
                    img, box, caishen_label, typical_width=typical_width,
                    next_left=next_left.get(tuple(box)))
                if realigned is None:
                    continue
                result, used_box = realigned
                # 多重搜索的统计代价用增益门补：救回分数必须比原框
                # 读数高出明确幅度，"勉强过线"不算对准证据。
                if float(result.get('score') or 0.0) \
                        - float(d.get('score') or 0.0) < 0.10:
                    continue
                result['original_label'] = d.get('label')
                result['original_score'] = d.get('score')
                result['box'] = list(used_box)
                result['region'] = 'exposed'
                self.meld_diagnostics[i] = result
                self.last_meld_boxes[i] = list(used_box)
                realigned_positions.append(pos)
            if len(realigned_positions) >= 2 and not (
                    self._meld_group_geometry_ok(
                        [(pos, self.last_meld_boxes[group[pos]])
                         for pos in realigned_positions],
                        typical_width=typical_width,
                        typical_pitch=typical_pitch)):
                for k, i in enumerate(group):
                    self.meld_diagnostics[i] = saved_diags[k]
                    self.last_meld_boxes[i] = saved_boxes[k]

    @staticmethod
    def _meld_group_geometry_ok(positioned_boxes, *, typical_width,
                                typical_pitch):
        """重对齐后（组内）联合几何校验：防多框各自串读邻牌。

        单框的中心护栏只能防单个框跑偏；整组多框若各自独立搜索，
        理论上可能串位还各自高分。这里只校验本次被重对齐的框彼此
        之间：x 单调递增、相邻不重叠、宽度合帧内典型值、组内相邻
        框的中心距合典型中心距。任一不合 → 整组重对齐作废、恢复
        原弃权（由调用方恢复快照）。
        """
        # 相邻框允许小幅重叠：搜索宽（典型宽）大于实际牌距时，对准的
        # 框天然交叠数像素（实机碰白例 5px）；串读邻牌的位移是半张牌
        # 量级，由中心距带宽兜底，不靠这条。
        overlap_tol = max(4.0, typical_width * 0.12) if typical_width else 4.0
        pts = [(pos, float(b[0]), float(b[2]))
               for pos, b in positioned_boxes]
        for (_p0, x0, _x1), (_p1, nx0, _nx1) in zip(pts, pts[1:]):
            if nx0 <= x0:
                return False
            if nx0 < _x1 - overlap_tol:
                return False
        if typical_width > 0:
            for _pos, x0, x1 in pts:
                if not typical_width * 0.75 <= x1 - x0 \
                        <= typical_width * 1.3:
                    return False
        if typical_pitch > 0:
            for (p0, x0, x1), (p1, nx0, nx1) in zip(pts, pts[1:]):
                if p1 - p0 != 1:
                    continue
                pitch = (nx0 + nx1 - x0 - x1) / 2.0
                if not typical_pitch * 0.8 <= pitch \
                        <= typical_pitch * 1.3:
                    return False
        return True

    def _realign_meld_box(self, img, box, caishen_label, *,
                          typical_width, next_left=None):
        """副露框有界重对齐：原框没对准牌面时，按原阈值换裁框重拍。

        2026-10-27 实机两例（5556 第 7 局 / 5554 第 12 局，同签名跨账号）：
        碰白板成第二副露组后，新组三框被列游程切分整体带偏——首框只剩
        62px、后两框相对牌面左移 13-18px。牌面本身明亮完整（白板 0.93+
        在同帧暗手里正常读出），坏的是裁框：白板全高边框字形的竖线被
        ``visible_border`` 误判，游程边界落在牌面内部。复核连拍两帧同读
        （落定签名一致）、事后 100 秒帧同读，是确定性坏读，不是动画帧。

        搜索范围严格有界：横移 -8..+30（按 1600 基准缩放）、宽度只取
        {原宽, 本帧典型宽 x0.9, 本帧典型宽}、右界不超过下一框左界 +30，
        且候选框中心与原框中心偏差不超过候选宽的 1/4（防读邻牌）。
        每个候选仍走 ``classify_crop`` 的原始 min_score/min_margin，
        只有被原标准接受的候选才采用（取分数最高者）；全找不到返回
        None，调用方保持原低分结论——弃权语义不变，阈值一字未动。
        """
        x0, y0, x1, y1 = (int(v) for v in box)
        scale = max(img.shape[1] / 1600.0, 0.5)
        widths = []
        for cand_w in (x1 - x0, round(typical_width * .9),
                       round(typical_width)):
            if cand_w and cand_w >= round(40 * scale) \
                    and int(cand_w) not in widths:
                widths.append(int(cand_w))
        if not widths:
            return None
        right_limit = img.shape[1]
        if next_left is not None:
            right_limit = min(right_limit,
                              int(next_left) + round(30 * scale))
        step = max(1, round(2 * scale))
        shifts = [0]
        for mag in range(step, round(30 * scale) + 1, step):
            shifts.append(mag)
            if mag <= round(8 * scale):
                shifts.append(-mag)
        center_x = (x0 + x1) / 2.0
        best = None
        for width in widths:
            for dx in shifts:
                nx0 = x0 + dx
                nx1 = nx0 + width
                if nx0 < 0 or nx1 > right_limit:
                    continue
                # 候选框中心必须留在原框中心 ±1/4 宽内：裁框只能微调
                # 对准本张牌，绝不允许整体挪到邻牌脸上去读邻牌的面。
                if abs((nx0 + nx1) / 2.0 - center_x) > width / 4.0:
                    continue
                if (nx0, nx1) == (x0, x1):
                    continue
                cand = self.classify_crop(img[y0:y1, nx0:nx1],
                                          caishen_label=caishen_label)
                if not cand.get('accepted'):
                    continue
                if best is None or float(cand.get('score') or 0) > float(
                        best[0].get('score') or 0):
                    best = (dict(cand), (nx0, y0, nx1, y1))
        if best is None:
            return None
        result, used_box = best
        result['reason'] = 'accepted_meld_realign'
        result['original_box'] = [x0, y0, x1, y1]
        return result, used_box

    def _return_invalid_trailing_platform_groups(self, concealed_boxes):
        """Move a confidently illegal trailing platform group back to the hand.

        Some live frames raise the first three concealed tiles to the same baseline
        as a real meld. Geometry then reports ``[3, 3]`` although the second triple
        is, for example, 四万/五万/白板. A real exposed group cannot have that
        shape. When at least one preceding group remains and the trailing group is
        fully read but illegal, the only conservative interpretation is that the
        trailing boxes are concealed. The correction is published in diagnostics.
        """
        sizes = list(self.detection_diagnostics.get('meld_groups') or [])
        if len(sizes) < 2 or sum(sizes) != len(self.meld_diagnostics):
            return list(concealed_boxes)
        moved = []
        concealed_boxes = list(concealed_boxes)
        while len(sizes) > 1:
            size = sizes[-1]
            faces = self.meld_diagnostics[-size:]
            if not all(d.get('accepted') for d in faces) \
                    or self._meld_face_group_ok(faces):
                break
            boxes = self.last_meld_boxes[-size:]
            ids = [int(d['tile_id']) for d in faces]
            del self.meld_diagnostics[-size:]
            del self.last_meld_boxes[-size:]
            sizes.pop()
            for item in faces:
                item['region'] = 'concealed'
                item['region_reclassified_reason'] = 'illegal_trailing_meld_shape'
            self.diagnostics = list(faces) + self.diagnostics
            concealed_boxes = list(boxes) + concealed_boxes
            moved.append({'size': size, 'tile_ids': ids,
                          'boxes': [list(box) for box in boxes],
                          'reason': 'illegal_trailing_meld_shape'})
        if moved:
            self.detection_diagnostics['meld_groups'] = sizes
            self.detection_diagnostics['meld_boxes'] = [
                list(box) for box in self.last_meld_boxes]
            self.detection_diagnostics['concealed_count'] = len(concealed_boxes)
            self.detection_diagnostics['platform_reclassified_groups'] = moved
        return concealed_boxes

    @staticmethod
    def _split_exposed_prefix(boxes, scale):
        """Cut the leading exposed-meld groups off the concealed hand.

        The game renders melds on a raised platform at the left: its tiles
        sit one row above the hand (bottoms ~16px higher at 1600x900) in
        groups of 3-4 positions. In-group neighbours are ~4px apart,
        inter-meld gaps are ~15px, and the platform-to-hand boundary is
        21-30px; hand neighbours never exceed ~11px. A gang stacks its 4th
        tile on the middle position, so one box of a meld group may sit a
        further ~26px higher (the 西杠 defect: per-box baseline tests
        rejected that box and then the whole group). Group shape decides
        instead: every box of the leading raised run belongs to the
        platform — internal gaps only split it into groups, they never
        disqualify single boxes. Label evidence is deliberately NOT used
        here: three identical faces may be a peng just as well as a gang.
        """
        if len(boxes) < 6:
            return [], list(boxes), []
        bottoms = [b[3] for b in boxes]
        typical_h = float(np.median([b[3]-b[1] for b in boxes]))
        typical_w = float(np.median([b[2]-b[0] for b in boxes]))
        # The hand owns the lowest row; the platform is clearly above it.
        hand_bottom = float(max(bottoms))
        raise_need = max(8.0*scale, typical_h*0.07)
        cut = 0
        for bottom in bottoms:
            if bottom < hand_bottom - raise_need:
                cut += 1
            else:
                break
        if cut < 3 or cut >= len(boxes):
            return [], list(boxes), []
        # The platform must be separated from the hand by a real gap.
        boundary = boxes[cut][0] - boxes[cut-1][2]
        if boundary < max(12.0*scale, typical_w*0.14):
            return [], list(boxes), []
        # Group sizes are reported for audit (a gang's 4th tile stacks onto
        # one of the 3 positions and must NOT be invented as an extra box);
        # an unusual group size never drags platform tiles back into the hand.
        meld_gap = max(12.0*scale, typical_w*0.14)
        groups, group = [], [boxes[0]]
        for b in boxes[1:cut]:
            if b[0] - group[-1][2] >= meld_gap:
                groups.append(group)
                group = [b]
            else:
                group.append(b)
        groups.append(group)
        return [b for g in groups for b in g], list(boxes[cut:]), [len(g) for g in groups]

    def classify_crop(self, crop, caishen_label=None, *, include_candidates=False):
        """Classify one tile crop; a 财-marked tile may be settled by its badge.

        caishen_label is this round's caishen in vision vocabulary. When it is
        unknown the badge is reported but never used to invent a tile.
        include_candidates exposes every loaded label's raw template score for
        read-only diagnostics. It never changes acceptance or ranks by rules.
        """
        self.load_templates()
        marked = caishen_badge(crop)
        # 副露"来源箭头"遮挡牌面上沿：先去遮挡再算签名（无箭头时 crop 原样）。
        crop, claim_marker = (strip_claim_marker(crop)
                              if self.allow_claim_marker else (crop, False))
        known = caishen_label in TILE_IDS
        # 只有"角标命中 + 本局财神已知"才做亮度补偿并计入：整手压暗是游戏
        # "请出牌"的瞬时状态，财神未知时角标牌也必须按未识别处理，两者都保持
        # 既有弃权契约（test_*_dimmed_frame / 金标基线）。
        # dim_gain_all：仅供离线实验/显式开启时，把"整手压暗"也当作可获得亮度
        # 补偿的情形。默认 False，既有弃权契约一个字节都不变。
        prepared = (normalise_face_brightness(crop)
                    if (marked and known) or self.dim_gain_all else crop)
        sig = tile_signature(prepared)
        if sig is None:
            result = {'tile_id': None, 'label': None, 'score': 0., 'margin': 0.,
                      'accepted': False, 'reason': 'no_glyph'}
            if marked and known:
                result.update(tile_id=TILE_IDS[caishen_label],
                              label=caishen_label, accepted=True,
                              reason='caishen_marked')
            result['caishen_marked'] = marked
            if include_candidates:
                result.update(candidates=[], candidates_complete=False)
            return result
        scores = self._matrix @ sig.ravel()
        by_label = {}
        for score, (name, tid, _) in zip(scores, self.templates):
            if name not in by_label or score > by_label[name][0]:
                by_label[name] = (float(score), tid)
        ranked = sorted(by_label.items(), key=lambda x: -x[1][0])
        label, (score, tid) = ranked[0]
        second = ranked[1][1][0] if len(ranked)>1 else 0.
        margin = score-second
        accepted = score >= self.min_score and margin >= self.min_margin
        result = {'tile_id': tid if accepted else None, 'label': label,
                'score': score, 'margin': margin, 'accepted': accepted,
                'runner_up': ranked[1][0] if len(ranked)>1 else None,
                'reason': 'accepted' if accepted else ('low_score' if score<self.min_score else 'ambiguous')}
        if include_candidates:
            result['candidates'] = [
                {'label': name, 'tile_id': candidate_id, 'score': candidate_score}
                for name, (candidate_score, candidate_id) in ranked
            ]
            result['candidates_complete'] = True
        # The red 财 banner is the game declaring "this tile is the caishen".
        # A known label therefore outranks an ambiguous glyph (九萬/八萬 land at
        # 0.845-0.854 here); the glyph reading is kept for audit.
        result['caishen_marked'] = marked
        if claim_marker:
            result['claim_marker'] = True
        if marked and known:
            result.update(tile_id=TILE_IDS[caishen_label], label=caishen_label,
                          accepted=True, reason='caishen_marked',
                          glyph_label=label, glyph_score=score)
        # 筒牌的"字形分数落后一点点"不再只能弃权：模板 top1/top2 都是筒牌时的
        # 歧义，改由独立判据（数圆点，见 pip_discriminator）裁决。只在这一个
        # 分支里生效，非歧义路径与改动前逐位一致。
        if not result['accepted'] and result['reason'] == 'ambiguous':
            self._resolve_pip_ambiguity(result, prepared)
        return result

    @staticmethod
    def _resolve_pip_ambiguity(result, prepared):
        """Settle a dot-vs-dot ambiguity by counting pips, or leave it abstained.

        Only called when the glyph classifier already abstained with
        reason='ambiguous'. The pip count is independent evidence, not a
        re-ranking of the two candidates:

        * count readable + standard layout + exactly one of {top1, top2} has
          that pip count  ->  adopt it, reason='pip_count', with the original
          score/margin preserved for audit;
        * count unreadable, layout non-standard, border-clipped face, or both/
          neither candidate matching  ->  the reading stays abstained.

        Args:
            result: the mutable classification dict from `classify_crop`.
            prepared: the exact crop pixels the glyph signature was built from.
        """
        from pip_discriminator import expected_pip_count, read_dot_pips
        top = result.get('label')
        runner = result.get('runner_up')
        first, second = expected_pip_count(top), expected_pip_count(runner)
        if first is None or second is None or first == second:
            return
        reading = read_dot_pips(prepared)
        result['pip_reading'] = reading.as_dict()
        result['pip_source_label'] = top
        result['pip_source_score'] = result.get('score')
        result['pip_source_margin'] = result.get('margin')
        if reading.count is None or not reading.layout_ok:
            return
        hits = [name for name, count in ((top, first), (runner, second))
                if count == reading.count]
        if len(hits) != 1:
            return
        chosen = hits[0]
        result.update(tile_id=TILE_IDS[chosen], label=chosen, accepted=True,
                      reason='pip_count', glyph_label=top,
                      glyph_score=result.get('score'))

    def _read_table_caishen(self, img):
        """Best-effort read of this round's caishen from the table sprite.

        Only used when a caller wants TileVision to resolve the label itself;
        the decision path stays opt-in so that frames analysed without a known
        caishen keep their previous, stricter behaviour.
        """
        try:
            from caishen_vision import detect_caishen
            return detect_caishen(img).label
        except Exception:
            return None

    def _gold_tile_reading(self, box, caishen_label):
        """Read one whole-gold tile as this round's caishen, or abstain.

        A solid gold face is the game's marking for the caishen tile, so the
        only honest label is this round's caishen. When the caller does not
        know it, the tile stays unread: reporting a guessed suit/number would
        hand the planner a fabricated hand, which is far worse than abstaining.
        """
        result = {'tile_id': None, 'label': None, 'score': 0., 'margin': 0.,
                  'accepted': False, 'reason': 'gold_tile_caishen_unknown',
                  'gold_tile': True, 'caishen_marked': True,
                  'box': list(box)}
        if caishen_label in TILE_IDS:
            result.update(tile_id=TILE_IDS[caishen_label], label=caishen_label,
                          accepted=True, reason='gold_tile_caishen')
        return result

    def recognize_hand(self, img, roi=None, caishen_label=None):
        self.load_templates()
        # 财神 label 只认调用方给的值：没有 label 就不动角标牌，保持既有严格行为
        # （整手压暗/未知财神仍弃权，见 test_*_dimmed_frame 与金标基线）。
        label = self.caishen_label if caishen_label is None else caishen_label
        count, boxes = self.count_tiles(img, roi)
        result, self.diagnostics = [], []
        self.last_melds,self.meld_diagnostics=[],[]
        detected = sorted(list(boxes) + list(self.last_meld_boxes), key=lambda b: b[0])
        typical_width = float(np.median([b[2] - b[0] for b in detected])) \
            if detected else 0.0
        next_left = {tuple(box): (detected[index + 1][0]
                                  if index + 1 < len(detected) else None)
                     for index, box in enumerate(detected)}
        classified_boxes = []
        # 整张纯金 = 本局财神牌（见 gold_face_mask 取样注释）。它不是"读不出字"的
        # 未知牌：有 caishen label 就按 label 计入，没有就严格弃权，绝不瞎猜。
        gold = {tuple(box) for box in getattr(self, 'last_gold_boxes', [])}
        for box in boxes:
            if tuple(box) in gold:
                d = self._gold_tile_reading(box, label)
                d['region'] = 'concealed'
                self.diagnostics.append(d)
                classified_boxes.append(tuple(box))
                continue
            d, fixed_box = self._classify_detected_box(
                img, box, label, typical_width=typical_width,
                next_left=next_left.get(tuple(box)),
                allow_dim_right_edge_retry=True)
            d['box'] = list(fixed_box)
            d['region'] = 'concealed'
            self.diagnostics.append(d)
            classified_boxes.append(fixed_box)
        boxes = classified_boxes
        classified_meld_boxes = []
        for box in self.last_meld_boxes:
            d, fixed_box = self._classify_detected_box(
                img, box, label, typical_width=typical_width,
                next_left=next_left.get(tuple(box)))
            d['box']=list(fixed_box);d['region']='exposed'
            self.meld_diagnostics.append(d)
            classified_meld_boxes.append(fixed_box)
        self.last_meld_boxes = classified_meld_boxes
        # Recover at most one weak tile in three consecutive equal-label boxes,
        # whether concealed or exposed. Both neighbours must have passed the
        # original classifier; a dark whole hand therefore still abstains.
        # The classifier's normal score and margin thresholds stay unchanged.
        def recover_triplet(diagnostics, group_boxes, region):
            originally_accepted = [d['accepted'] for d in diagnostics]

            def face_at(index):
                x0,y0,x1,y1 = group_boxes[index]
                face = face_region(img[y0:y1, x0:x1])
                return cv2.resize(cv2.cvtColor(face, cv2.COLOR_BGR2GRAY), (48, 64))

            for idx, d in enumerate(diagnostics):
                if (originally_accepted[idx]
                        or d.get('reason') not in ('low_score', 'ambiguous')
                        or d.get('score', 0) < .5 or not d.get('label')):
                    continue
                last_start = min(idx, len(diagnostics) - 3)
                for start in range(max(0, idx - 2), last_start + 1):
                    good = [j for j in range(start, start + 3)
                            if j != idx and originally_accepted[j]
                            and diagnostics[j]['label'] == d['label']]
                    if len(good) != 2:
                        # Run completion: a chi group holds three DIFFERENT
                        # labels, so equal-label correlation can never fire.
                        # When the two accepted neighbours plus the weak
                        # tile's own top-1 label form one consecutive
                        # same-suit run, the sequence is the evidence
                        # (20261024_0815: exposed 2-3-4 dots lost its leading
                        # 2 at score .51 and the whole frame abstained).
                        peers = [j for j in range(start, start + 3)
                                 if j != idx and originally_accepted[j]]
                        if len(peers) == 2 and self._same_suit_run(
                                [TILE_IDS[diagnostics[j]['label']] for j in peers]
                                + [TILE_IDS[d['label']]]):
                            d.update(accepted=True, tile_id=TILE_IDS[d['label']],
                                     reason=f'{region}_run_correlated')
                            break
                        continue
                    weak_face = face_at(idx)
                    similarity = max(float(cv2.matchTemplate(
                        weak_face, face_at(j), cv2.TM_CCOEFF_NORMED)[0, 0])
                        for j in good)
                    if similarity >= .95:
                        d.update(accepted=True, tile_id=TILE_IDS[d['label']],
                                 reason=f'{region}_triplet_correlated',
                                 group_similarity=similarity)
                        break

        recover_triplet(self.diagnostics, boxes, 'concealed')
        recover_triplet(self.meld_diagnostics, self.last_meld_boxes, 'exposed')
        # 相关性兜底之后仍整组读不出的副露框，最后才做有界重对齐
        # （2026-10-27 碰白板第二组框带偏事故，见 _realign_failed_meld_boxes）。
        self._realign_failed_meld_boxes(
            img, label, typical_width=typical_width, next_left=next_left)
        boxes = self._return_invalid_trailing_platform_groups(boxes)
        # 财神未知时金色牌不参与计数：把弃权原因提到 detection_diagnostics，
        # 让台账写"gold_tile_caishen_unknown"而不是含糊的 "识牌不完整"。
        unknown_gold = [d for d in self.diagnostics
                        if d.get('reason') == 'gold_tile_caishen_unknown']
        if unknown_gold:
            self.detection_diagnostics['reason'] = 'gold_tile_caishen_unknown'
            self.detection_diagnostics['gold_tiles_without_caishen'] = [
                list(d['box']) for d in unknown_gold]
        count = len(boxes)
        result = [(d['tile_id'], *d['box']) for d in self.diagnostics if d['accepted']]
        self.last_melds = [(d['tile_id'], *d['box']) for d in self.meld_diagnostics
                           if d['accepted']]
        over = {tid for tid,n in Counter(t[0] for t in result+self.last_melds).items() if n>4}
        if over:
            # Never silently trim an impossible hand into a plausible one.
            for d in self.diagnostics+self.meld_diagnostics:
                if d['tile_id'] in over:
                    d.update(accepted=False, tile_id=None, reason='more_than_four')
            result = [t for t in result if t[0] not in over]
            self.last_melds=[t for t in self.last_melds if t[0] not in over]
        self.last_complete = (count>0 and len(result)==count
            and len(self.last_melds)==len(self.last_meld_boxes)
            and not self.detection_diagnostics.get('unresolved_regions')
            and not unknown_gold)
        return result


def detect_hand(png_bytes: bytes) -> list[int]:
    """Return a complete closed tea hand, or [] for invalid/incomplete images.

    Missing templates remain errors so configuration faults are not hidden.
    """
    if not png_bytes:
        return []
    img = cv2.imdecode(np.frombuffer(png_bytes, dtype=np.uint8), cv2.IMREAD_COLOR)
    if img is None:
        return []
    from mode_vision import detect_tea_player_count
    if detect_tea_player_count(img) != 2:
        return []
    tv = TileVision(template_dir=BASE_DIR.parent / '采集' / 'templates' / 'tea_tiles')
    result = tv.recognize_hand(img)
    if not tv.last_complete or tv.last_meld_boxes or len(result) not in (16, 17):
        return []
    return [tile_id for tile_id, *_ in result]
