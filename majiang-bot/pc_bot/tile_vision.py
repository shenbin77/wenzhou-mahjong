"""Screenshot tile detection and conservative, colour-aware template classification.

The 34-label visual vocabulary includes honours for rejecting sample-mode frames;
the target game's engine vocabulary remains 27 suits plus red-Zhong (55).
No model service, screenshots generated by AI, or emulator input is used here.
"""
from collections import Counter
from pathlib import Path
import json

import cv2
import numpy as np

BASE_DIR = Path(__file__).resolve().parent
TILE_IDS = {**{f'w{i}': i for i in range(1, 10)},
            **{f't{i}': 20+i for i in range(1, 10)},
            **{f's{i}': 40+i for i in range(1, 10)},
            'hongzhong': 55, 'dong': 61, 'nan': 62, 'xi': 63,
            'bei': 64, 'fa': 66, 'bai': 67}
TARGET_IDS = set(range(1, 10)) | set(range(21, 30)) | set(range(41, 50)) | {55}


class NoTemplatesError(RuntimeError):
    pass


def _read(path):
    """imdecode also supports non-ASCII Windows checkout paths."""
    return cv2.imdecode(np.fromfile(str(path), dtype=np.uint8), cv2.IMREAD_COLOR)


def face_region(crop):
    """Remove gold bases/selection caps using the longest cream row interval."""
    if crop is None or crop.size == 0:
        raise ValueError('empty tile crop')
    h, w = crop.shape[:2]
    hsv = cv2.cvtColor(crop, cv2.COLOR_BGR2HSV)
    cream = (hsv[:, :, 1] < 90) & (hsv[:, :, 2] > 65)
    # Broad 發/bird glyphs can touch either side; use low cream coverage and
    # bridge only short glyph interruptions, never the tall gold selection cap.
    a,b=max(1,int(w*.05)),min(w-1,int(w*.95))
    rows = (np.mean(cream[:,a:b],axis=1) > .23).astype(np.uint8)
    rows = cv2.morphologyEx(rows[:,None],cv2.MORPH_CLOSE,np.ones((7,1),np.uint8))[:,0]>0
    intervals, start = [], None
    for i, on in enumerate(np.r_[rows, False]):
        if on and start is None:
            start = i
        if not on and start is not None:
            intervals.append((start, i)); start = None
    if not intervals:
        return crop
    y0, y1 = max(intervals, key=lambda p: p[1]-p[0])
    if y1-y0 < h*.35:
        return crop
    return crop[y0:y1, :]


def tile_signature(crop):
    """Fit real glyph pixels to a fixed canvas; discard skin brightness changes.

    Red, green and dark ink are separate channels. White faces alone therefore
    cannot produce a high match, unlike whole-tile grayscale correlation.
    """
    face = face_region(crop)
    h, w = face.shape[:2]
    dy, dx = max(2, int(h*.05)), max(2, int(w*.07))
    inner = face[dy:h-dy, dx:w-dx]
    if inner.size == 0:
        return None
    hsv = cv2.cvtColor(inner, cv2.COLOR_BGR2HSV)
    gray = cv2.cvtColor(inner, cv2.COLOR_BGR2GRAY)
    hue, sat, val = (hsv[:, :, i] for i in range(3))
    background = float(np.percentile(gray, 75))
    red = ((hue < 19) | (hue > 165)) & (sat > 100) & (val > 35)
    green = (hue >= 32) & (hue <= 95) & (sat > 90) & (val > 35)
    # Navy numerals are highly saturated too; exclude red/green by hue instead
    # of excluding all saturated dark ink (which loses the numeral above 萬).
    dark = (gray < max(35., background*.62)) & ~red & ~green
    # The actual target recordings overlay a yellow 財 word on a red corner
    # triangle. Detect both colours together; an ordinary red tile stroke or
    # a gold bevel alone must not trigger this mask. Only the observed corner
    # is ignored, preserving the real glyph pixels underneath/elsewhere.
    cy,cx=max(1,round(inner.shape[0]*.40)),max(1,round(inner.shape[1]*.42))
    badge_red=(hue[:cy,:cx]<8)&(sat[:cy,:cx]>130)&(val[:cy,:cx]>90)
    badge_yellow=(hue[:cy,:cx]>=18)&(hue[:cy,:cx]<=40)&(sat[:cy,:cx]>110)&(val[:cy,:cx]>150)
    if np.count_nonzero(badge_red)>cy*cx*.10 and np.count_nonzero(badge_yellow)>cy*cx*.05:
        search_h,search_w=round(inner.shape[0]*.65),round(inner.shape[1]*.72)
        fill=(hue[:search_h,:search_w]<8)&(sat[:search_h,:search_w]>130)&(val[:search_h,:search_w]>90)
        fy,fx=np.where(fill)
        if len(fx):
            bw,bh=float(np.percentile(fx,99)+3),float(np.percentile(fy,99)+3)
            yy,xx=np.indices(inner.shape[:2])
            triangle=xx/max(1,bw)+yy/max(1,bh)<=1.10
            red[triangle]=False;green[triangle]=False;dark[triangle]=False
    ink = (dark | red | green).astype(np.uint8)
    num, labels, stats, _ = cv2.connectedComponentsWithStats(ink, 8)
    clean = np.zeros_like(ink)
    for i in range(1, num):
        sx,sy,sw,sh,area=stats[i]
        # Small black/gold direction markers sit on the top border. Keep broad
        # or tall tile strokes; remove only a separate short border component.
        if sy<=1 and sh<inner.shape[0]*.17 and sw<inner.shape[1]*.55:
            continue
        if stats[i, cv2.CC_STAT_AREA] >= max(4, inner.shape[0]*inner.shape[1]*.001):
            clean[labels == i] = 1
    ys, xs = np.where(clean > 0)
    if len(xs) < 16:
        return None
    x0, x1, y0, y1 = xs.min(), xs.max()+1, ys.min(), ys.max()+1
    glyph = np.stack((dark, red, green), axis=2).astype(np.float32)
    glyph *= clean[:, :, None]
    glyph = glyph[y0:y1, x0:x1]
    gh, gw = glyph.shape[:2]
    scale = min(56/gw, 80/gh)
    nw, nh = max(1, round(gw*scale)), max(1, round(gh*scale))
    glyph = cv2.resize(glyph, (nw, nh), interpolation=cv2.INTER_AREA)
    canvas = np.zeros((88, 64, 3), np.float32)
    cy, cx = (88-nh)//2, (64-nw)//2
    canvas[cy:cy+nh, cx:cx+nw] = glyph
    # Light blur tolerates anti-aliasing/one-pixel edges without losing strokes.
    canvas = cv2.GaussianBlur(canvas, (3, 3), .6)
    norm = float(np.linalg.norm(canvas))
    return canvas / norm if norm > .001 else None


class TileVision:
    def __init__(self, template_dir=None, min_score=.82, min_margin=.055):
        self.template_dir = Path(template_dir or BASE_DIR/'templates_hongzhong_v2')
        self.min_score = min_score
        self.min_margin = min_margin
        self.diagnostics = []
        self.detection_diagnostics = {}
        self.last_meld_boxes = []
        self.last_melds = []
        self.meld_diagnostics = []
        self.last_complete = False
        self.templates = []
        self._matrix = None
        self._loaded = False

    def load_templates(self):
        if self._loaded:
            return
        manifest = self.template_dir/'manifest.json'
        if not manifest.exists():
            raise NoTemplatesError(f'verified template manifest missing: {manifest}')
        records = json.loads(manifest.read_text(encoding='utf-8'))['templates']
        for rec in records:
            crop = _read(self.template_dir/rec['file'])
            sig = tile_signature(crop)
            if sig is None:
                raise NoTemplatesError(f'template has no usable glyph: {rec["file"]}')
            self.templates.append((rec['label'], TILE_IDS[rec['label']], sig))
        if not self.templates:
            raise NoTemplatesError('no verified tile templates')
        self._matrix = np.stack([x[2].ravel() for x in self.templates])
        self._loaded = True

    def count_tiles(self, img, roi=None):
        """Return concealed xyxy boxes; expose separate left meld-box geometry.

        Only a visibly smaller, raised left group of 3/4 separated faces is
        labelled exposed. Geometry does not infer peng/gang type or who fed it.
        """
        self.last_meld_boxes=[]
        h, w = img.shape[:2]
        if roi is None:
            roi = (0, round(h*.8), w, h)
        x0, y0, x1, y1 = map(int, roi)
        x0, y0, x1, y1 = max(0,x0), max(0,y0), min(w,x1), min(h,y1)
        if x1 <= x0 or y1 <= y0:
            self.detection_diagnostics={'reason':'empty_roi','unresolved_regions':[]}
            return 0, []
        band = img[y0:y1, x0:x1]
        hsv = cv2.cvtColor(band, cv2.COLOR_BGR2HSV)
        mask = cv2.inRange(hsv, np.array([0, 0, 70]), np.array([179, 85, 255]))
        scale = w/1600
        # Find actual dark vertical borders. The 90th percentile suppresses
        # glyph ink (each glyph column still has cream rows), while a border is
        # darker throughout the face. This works with both the 90px sample skin
        # and 83/113px archived target layouts; screen width is not tile pitch.
        gray=cv2.cvtColor(band,cv2.COLOR_BGR2GRAY)
        # Upper table discards/selection markers may overhang one hand tile.
        # Estimate skin from the lower two thirds, where the hand faces lie.
        skin_rows=gray[gray.shape[0]//3:]
        column_skin=np.percentile(skin_rows,90,axis=0).astype(np.float32)
        edge_window=max(5,round(17*scale))|1
        local_skin=cv2.dilate(column_skin[None,:],np.ones((1,edge_window),np.uint8))[0]
        low_skin=column_skin < local_skin*.82
        # A raised card / bright indicator above one tile can alter a broad
        # part of the percentile profile. Real face borders are narrow; do not
        # erase wide patches and thereby silently lose a selected tile.
        visible_border=np.zeros_like(low_skin)
        ld=np.diff(np.r_[False,low_skin,False].astype(np.int8))
        for a,b in zip(np.flatnonzero(ld==1),np.flatnonzero(ld==-1)):
            if b-a<=max(5,round(11*scale)):
                visible_border[a:b]=True
        # A 財 corner overlay plus a long 中 stroke can cover most of a column;
        # a few real cream rows are sufficient once vertical borders are known.
        on = (np.count_nonzero(mask, axis=0) >= max(12*scale, band.shape[0]*.07))
        on &= ~visible_border
        changes = np.diff(np.r_[False,on,False].astype(np.int8))
        runs = zip(np.flatnonzero(changes==1), np.flatnonzero(changes==-1))
        boxes,unresolved = [],[]
        for a,b in runs:
            if b-a < 48*scale:
                continue
            bx,ex=int(a),int(b);bw=ex-bx
            rows=np.flatnonzero(np.count_nonzero(mask[:,bx:ex],axis=1) >= bw*.4)
            if not len(rows):continue
            by,ey=int(rows[0]),int(rows[-1])+1;bh=ey-by
            candidate=band[by:ey,bx:ex]
            face=face_region(candidate)
            offset=(face.ctypes.data-candidate.ctypes.data)//candidate.strides[0]
            by+=int(offset);ey=by+face.shape[0];bh=ey-by
            if bw>125*scale:
                unresolved.append([x0+bx,y0+by,x0+ex,y0+ey])
                continue # Do not invent a grid when real separators are hidden.
            if not (48*scale<=bw<=125*scale and 80*scale<=bh<=180*scale):continue
            if not (.42<=bw/bh<=1.05):continue
            boxes.append((x0+bx,y0+by,x0+ex,y0+ey))
        boxes.sort(key=lambda b: b[0])
        visible_count=len(boxes)
        if len(boxes)>=6:
            baseline=float(np.median([b[3] for b in boxes]))
            typical_h=float(np.median([b[3]-b[1] for b in boxes]))
            typical_w=float(np.median([b[2]-b[0] for b in boxes]))
            cut=0
            for b in boxes:
                if b[3] < baseline-max(8*scale,typical_h*.07) and b[2]-b[0] < typical_w*.98:
                    cut+=1
                else:break
            if cut in (3,4) and cut<len(boxes):
                group=boxes[:cut];gap=boxes[cut][0]-group[-1][2]
                tight=max(b[3] for b in group)-min(b[3] for b in group)<=4*scale
                if gap>=8*scale and tight:
                    self.last_meld_boxes=group
                    boxes=boxes[cut:]
        self.detection_diagnostics={'reason':'visible_borders','unresolved_regions':unresolved,
                                    'roi':[x0,y0,x1,y1], 'visible_count':visible_count,
                                    'concealed_count':len(boxes),'meld_boxes':[list(b) for b in self.last_meld_boxes]}
        return len(boxes), boxes

    def classify_crop(self, crop):
        self.load_templates()
        sig = tile_signature(crop)
        if sig is None:
            return {'tile_id': None, 'label': None, 'score': 0., 'margin': 0.,
                    'accepted': False, 'reason': 'no_glyph'}
        scores = self._matrix @ sig.ravel()
        by_label = {}
        for score, (name, tid, _) in zip(scores, self.templates):
            if name not in by_label or score > by_label[name][0]:
                by_label[name] = (float(score), tid)
        ranked = sorted(by_label.items(), key=lambda x: -x[1][0])
        label, (score, tid) = ranked[0]
        second = ranked[1][1][0] if len(ranked)>1 else 0.
        margin = score-second
        accepted = score >= self.min_score and margin >= self.min_margin
        return {'tile_id': tid if accepted else None, 'label': label,
                'score': score, 'margin': margin, 'accepted': accepted,
                'runner_up': ranked[1][0] if len(ranked)>1 else None,
                'reason': 'accepted' if accepted else ('low_score' if score<self.min_score else 'ambiguous')}

    def recognize_hand(self, img, roi=None):
        self.load_templates()
        count, boxes = self.count_tiles(img, roi)
        result, self.diagnostics = [], []
        self.last_melds,self.meld_diagnostics=[],[]
        for box in boxes:
            x0,y0,x1,y1 = box
            d = self.classify_crop(img[y0:y1,x0:x1])
            d['box'] = list(box)
            d['region'] = 'concealed'
            self.diagnostics.append(d)
            if d['accepted']:
                result.append((d['tile_id'],*box))
        for box in self.last_meld_boxes:
            x0,y0,x1,y1=box
            d=self.classify_crop(img[y0:y1,x0:x1]);d['box']=list(box);d['region']='exposed'
            self.meld_diagnostics.append(d)
            if d['accepted']:self.last_melds.append((d['tile_id'],*box))
        over = {tid for tid,n in Counter(t[0] for t in result+self.last_melds).items() if n>4}
        if over:
            # Never silently trim an impossible hand into a plausible one.
            for d in self.diagnostics+self.meld_diagnostics:
                if d['tile_id'] in over:
                    d.update(accepted=False, tile_id=None, reason='more_than_four')
            result = [t for t in result if t[0] not in over]
            self.last_melds=[t for t in self.last_melds if t[0] not in over]
        self.last_complete = (count>0 and len(result)==count
            and len(self.last_melds)==len(self.last_meld_boxes)
            and not self.detection_diagnostics.get('unresolved_regions'))
        return result
